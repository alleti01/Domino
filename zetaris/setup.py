"""One command to (re)build Domino's Zetaris layer, as the admin login from .env.

    python3 zetaris/setup.py                 files + sources + USL + access
    python3 zetaris/setup.py --rebuild-usl   remove the USL first, then rebuild it and re-grant access
    python3 zetaris/setup.py --dry-run       print the statements without running anything

Steps:
  files   regenerate the source CSVs and copy them into the Zetaris file store (domino/)
  catalogdb  start the PostgreSQL "database catalog" (container domino-catalog-db on Zetaris's network)
             and load its tables (access_grants, table_inventory); Zetaris reads them over JDBC
  sources sql/01_sources.sql   register the files as tables in domino_src
  usl     sql/02_usl.sql       compile and activate the USL lightning.metastore.domino.systems
  dq      sql/04_dq.sql        register the custom data-quality rules (re-run after every USL rebuild)
  access  sql/03_access.sql    read-only grant for the agent user (re-run after every USL rebuild)
  report  dq_report.py         run every data-quality rule and save the findings the agent sees as dq_issues

"Already exists" errors are skipped, so it is safe to re-run. Never uses `docker compose down -v`.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from data_layer import config, query_log  # noqa: E402
from data_layer.zetaris_client import ZetarisClient, ZetarisError  # noqa: E402

import build_sources  # noqa: E402

DRIVER = "zetaris-driver-1"
CATALOG_DB = "domino-catalog-db"
CATALOG_TABLES = ("access_grants", "table_inventory")
# Small lookup tables built inside PostgreSQL. The edge query needs "first row per principal / database";
# aggregating a JDBC table inside the big UNION ALL trips a Spark planning error, so Postgres does it.
CATALOG_REFS = {
    "principal_refs": "SELECT system_id, principal_name, MIN(source_row_id) AS src FROM access_grants GROUP BY system_id, principal_name",
    "database_refs": "SELECT system_id, database_name, MIN(source_row_id) AS src FROM table_inventory GROUP BY system_id, database_name",
}
NETWORK = "zetaris_default"
STEPS = ("files", "catalogdb", "sources", "usl", "dq", "access", "report")
SQL_FILES = {"sources": "01_sources.sql", "usl": "02_usl.sql", "dq": "04_dq.sql", "access": "03_access.sql"}
SQL_TIMEOUT_S = 600


def statements(path: Path, values: dict) -> list:
    """Split on lines holding only ';' (so a multi-table COMPILE USL stays whole); drop comment lines."""
    out, current = [], []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() == ";":
            if current:
                out.append("\n".join(current).strip().format(**values))
            current = []
        elif not line.lstrip().startswith("--"):
            current.append(line)
    if "".join(current).strip():
        out.append("\n".join(current).strip().format(**values))
    return [s for s in out if s]


def _docker(*args: str) -> str:
    return subprocess.run(["docker", *args], check=True, capture_output=True, text=True, timeout=60).stdout.strip()


def copy_files(dry_run: bool) -> None:
    build_sources.main()
    roots = _docker("exec", DRIVER, "sh", "-c", "ls -d /home/zetaris/customer-data/*/file-store").splitlines()
    if len(roots) != 1:
        raise SystemExit(f"Expected one organisation file store, found: {roots}")
    target = roots[0] + "/domino"
    # The private set (public + held-out rows) wins when it exists; it never enters the repo.
    private = build_sources.private_out_dir()
    source_dir = private if any(private.glob("*.csv")) else build_sources.OUT_DIR
    files = sorted(source_dir.glob("*.csv"))
    print(f"copy {len(files)} files from {'private folder' if source_dir == private else 'repo'} -> {DRIVER}:{target}")
    if dry_run:
        return
    _docker("exec", "-u", "0", DRIVER, "mkdir", "-p", target)
    for f in files:
        _docker("cp", str(f), f"{DRIVER}:{target}/{f.name}")
    _docker("exec", "-u", "0", DRIVER, "chown", "-R", "1001:1001", target)


def catalog_password() -> str:
    """The catalog database's password: from .env, or generated once and saved there (never printed)."""
    pw = config.get("DOMINO_CATALOG_DB_PASSWORD")
    if not pw:
        import secrets
        pw = "c" + secrets.token_hex(16)
        env = config.ENV_FILE
        with env.open("a", encoding="utf-8") as fh:
            fh.write(f"\n# Local PostgreSQL catalog database (generated by zetaris/setup.py)\nDOMINO_CATALOG_DB_PASSWORD={pw}\n")
        os.chmod(env, 0o600)
        os.environ["DOMINO_CATALOG_DB_PASSWORD"] = pw
        print("  generated DOMINO_CATALOG_DB_PASSWORD in .env")
    return pw


def start_catalog_db(dry_run: bool) -> None:
    """Run PostgreSQL as the real system behind the db_catalog source, and (re)load its tables."""
    import csv as csvmod
    private = build_sources.private_out_dir()
    source_dir = private if any(private.glob("*.csv")) else build_sources.OUT_DIR
    print(f"start {CATALOG_DB} on {NETWORK}; load {', '.join(CATALOG_TABLES)} from {'private folder' if source_dir == private else 'repo'}")
    if dry_run:
        return
    pw = catalog_password()
    running = subprocess.run(["docker", "ps", "-q", "-f", f"name=^{CATALOG_DB}$"], capture_output=True, text=True).stdout.strip()
    if not running:
        subprocess.run(["docker", "rm", "-f", CATALOG_DB], capture_output=True)
        _docker("run", "-d", "--name", CATALOG_DB, "--network", NETWORK, "--restart", "unless-stopped",
                "-e", "POSTGRES_DB=catalog", "-e", "POSTGRES_USER=domino_catalog", "-e", f"POSTGRES_PASSWORD={pw}",
                "postgres:16-alpine")
    for _ in range(60):
        if subprocess.run(["docker", "exec", CATALOG_DB, "pg_isready", "-U", "domino_catalog", "-d", "catalog"],
                          capture_output=True).returncode == 0:
            break
        time.sleep(1)
    for table in CATALOG_TABLES:
        path = source_dir / f"{table}.csv"
        with path.open(encoding="utf-8") as fh:
            columns = next(csvmod.reader(fh))
        psql = ["docker", "exec", "-i", CATALOG_DB, "psql", "-q", "-v", "ON_ERROR_STOP=1", "-U", "domino_catalog", "-d", "catalog"]
        ddl = f"DROP TABLE IF EXISTS {table}; CREATE TABLE {table} (" + ", ".join(f"{c} text" for c in columns) + ");"
        for args, data in ((["-c", ddl], None),
                           (["-c", f"COPY {table} FROM STDIN WITH (FORMAT csv, HEADER true)"], path.read_text(encoding="utf-8"))):
            proc = subprocess.run(psql + args, input=data, capture_output=True, text=True, timeout=60)
            if proc.returncode != 0:
                raise SystemExit(f"loading {table} into {CATALOG_DB} failed: {proc.stderr.strip()[:400]}")
        count = _docker("exec", CATALOG_DB, "psql", "-tA", "-U", "domino_catalog", "-d", "catalog", "-c", f"SELECT count(*) FROM {table}")
        print(f"  loaded {table}: {count} rows")
    for name, select in CATALOG_REFS.items():
        _docker("exec", CATALOG_DB, "psql", "-q", "-v", "ON_ERROR_STOP=1", "-U", "domino_catalog", "-d", "catalog",
                "-c", f"DROP TABLE IF EXISTS {name}; CREATE TABLE {name} AS {select};")
        print(f"  built {name}")


def run_sql(client, name: str, values: dict, dry_run: bool) -> int:
    failures = 0
    for sql in statements(HERE / "sql" / SQL_FILES[name], values):
        first_line = sql.splitlines()[0][:100]
        if dry_run:
            print(f"  [dry-run] {first_line}")
            continue
        try:
            res = client.run(sql, read_only=False, timeout_s=SQL_TIMEOUT_S, purpose=f"setup:{name}")
            print(f"  ok    {first_line}  ({res.duration_ms} ms)")
        except ZetarisError as error:
            if "already exist" in str(error).lower() or "already been granted" in str(error).lower():
                print(f"  skip  {first_line}  (already exists)")
            else:
                failures += 1
                print(f"  FAIL  {first_line}\n        {query_log.redact(str(error))[:600]}")
    return failures


def main() -> int:
    parser = argparse.ArgumentParser(description="Build Domino's Zetaris sources and USL")
    parser.add_argument("--steps", default=",".join(STEPS), help=f"comma-separated subset of {STEPS}")
    parser.add_argument("--rebuild-usl", action="store_true", help="remove the USL before compiling it again")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    steps = [s.strip() for s in args.steps.split(",") if s.strip()]
    unknown = sorted(set(steps) - set(STEPS))
    if unknown:
        parser.error(f"unknown steps: {unknown}")

    values = {"agent_user": config.get("ZETARIS_AGENT_USERNAME") or "",
              "catalog_password": (catalog_password() if "sources" in steps and not args.dry_run else "<hidden>")}
    if "access" in steps and not values["agent_user"]:
        raise SystemExit("Set ZETARIS_AGENT_USERNAME in .env (python3 -m data_layer set-credentials).")
    client = None if args.dry_run else ZetarisClient("admin")

    failures = 0
    for step in steps:
        print(f"== {step}")
        if step == "files":
            copy_files(args.dry_run)
            continue
        if step == "catalogdb":
            start_catalog_db(args.dry_run)
            continue
        if step == "report":
            if not args.dry_run:
                import dq_report
                failures += dq_report.main()
            continue
        if step == "usl" and args.rebuild_usl and not args.dry_run:
            try:
                client.run("REMOVE USL systems NAMESPACE lightning.metastore.domino", read_only=False,
                           timeout_s=SQL_TIMEOUT_S, purpose="setup:usl")
                print("  ok    REMOVE USL systems")
            except ZetarisError as error:
                print(f"  note  REMOVE USL: {str(error)[:200]}")
        failures += run_sql(client, step, values, args.dry_run)
    print(f"\n{'Done' if not failures else f'{failures} statement(s) failed'}.")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
