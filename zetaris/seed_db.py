"""Schema and seed data for your own database: loads Domino's nine synthetic source tables anywhere.

Reads only the repo's CSVs (zetaris/sources/, the released worlds). Every column is text, as Zetaris returns
it; the USL does the casting. Each table's key is source_row_id. All data is synthetic.

    python3 zetaris/seed_db.py --sql > domino_seed.sql     portable SQL (PostgreSQL, SQLite, MySQL, ...)
        psql "postgresql://user@host:5432/db" -v ON_ERROR_STOP=1 -f domino_seed.sql
    python3 zetaris/seed_db.py --sqlite domino.db          a ready SQLite file, nothing to install
    python3 zetaris/seed_db.py --zetaris-sql               the statements that point Zetaris at that database

Re-running replaces the tables (DROP TABLE IF EXISTS). Also builds principal_refs and database_refs, the two
small lookup tables the USL edge query reads (see zetaris/README.md, "JDBC aggregation").
"""

from __future__ import annotations

import argparse
import csv
import sqlite3
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from build_sources import OUT_DIR, TABLES  # noqa: E402  (repo CSVs only, never the private folder)
from setup import CATALOG_REFS  # noqa: E402

BATCH = 200


def _rows(table: str) -> list:
    with (OUT_DIR / f"{table}.csv").open(newline="", encoding="utf-8") as fh:
        reader = csv.reader(fh)
        if next(reader) != TABLES[table]:
            raise SystemExit(f"{table}.csv header differs from build_sources.TABLES; run zetaris/build_sources.py")
        return list(reader)


def _ddl(table: str) -> str:
    cols = ", ".join(f"{c} text NOT NULL PRIMARY KEY" if c == "source_row_id" else f"{c} text" for c in TABLES[table])
    return f"CREATE TABLE {table} ({cols})"


def _quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def sql_script() -> str:
    out = ["-- Domino synthetic source tables. Generated by zetaris/seed_db.py; all data is synthetic.", ""]
    for table in TABLES:
        rows = _rows(table)
        out += [f"DROP TABLE IF EXISTS {table};", _ddl(table) + ";"]
        for i in range(0, len(rows), BATCH):
            values = ",\n  ".join("(" + ", ".join(_quote(v) for v in row) + ")" for row in rows[i:i + BATCH])
            out.append(f"INSERT INTO {table} ({', '.join(TABLES[table])}) VALUES\n  {values};")
        out.append("")
    for name, select in CATALOG_REFS.items():
        out += [f"DROP TABLE IF EXISTS {name};", f"CREATE TABLE {name} AS {select};", ""]
    return "\n".join(out)


def build_sqlite(path: Path) -> dict:
    conn = sqlite3.connect(str(path))
    try:
        conn.executescript(sql_script())
        conn.commit()
        return {t: conn.execute(f"SELECT count(*) FROM {t}").fetchone()[0] for t in list(TABLES) + list(CATALOG_REFS)}
    finally:
        conn.close()


def zetaris_sql() -> str:
    tables = ", ".join(f'"{t}"' for t in list(TABLES) + list(CATALOG_REFS))
    return f"""-- Run as the Zetaris admin, one statement per request, with your own connection details.
CREATE DATASOURCE my_domino_db DESCRIBE BY "Domino sources in my database"
OPTIONS (jdbcdriver "org.postgresql.Driver", jdbcurl "jdbc:postgresql://<host>:5432/<database>",
username "<user>", password "<password>")

REGISTER DATASOURCE TABLES ({tables}) FROM my_domino_db

-- Then query them as my_domino_db.<table>, e.g. SELECT count(*) FROM my_domino_db.access_grants
-- Our USL (zetaris/sql/02_usl.sql) reads catalog_db.* and domino_src.*; replace those prefixes with
-- my_domino_db to build it from your database instead."""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--sql", action="store_true", help="print portable SQL to stdout")
    mode.add_argument("--sqlite", metavar="PATH", help="write a SQLite database file")
    mode.add_argument("--zetaris-sql", action="store_true", help="print the Zetaris datasource statements")
    args = parser.parse_args()
    if args.sql:
        sys.stdout.write(sql_script() + "\n")
    elif args.zetaris_sql:
        print(zetaris_sql())
    else:
        path = Path(args.sqlite)
        path.unlink(missing_ok=True)
        for table, count in build_sqlite(path).items():
            print(f"  {table}: {count} rows")
        print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
